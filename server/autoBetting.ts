const AUTO_BET_STATE_FILE = path.join(process.cwd(), 'server', 'autoBetState.json');
const SUPABASE_SETTINGS_ROW_ID = 2; // Row 1 is notification_settings; Row 2 stores auto_bet_state

interface PersistedAutoBetState {
  config: AutoBetConfig;
  // Map of `${dateStr}__${mode}` -> array of matchIds / pairKeys already generated by automation
  generatedHistory: Record<string, string[]>;
}

let state: PersistedAutoBetState = {
  config: { ...DEFAULT_AUTO_BET_CONFIG },
  generatedHistory: {},
};

let stateLoaded = false;
let activeRunPromise: Promise<AutoBetRunResult> | null = null;
let activeSyncPromise: Promise<{ updatedCount: number; settledBets: BetItem[] }> | null = null;

export interface AutoBetRunResult {
  success: boolean;
  date: string;
  createdBets: BetItem[];
  skippedReason?: string;
  preview: AutoBetPreview;
}

function sanitizeConfig(partial?: Partial<AutoBetConfig>): AutoBetConfig {
  const merged: AutoBetConfig = {
    ...DEFAULT_AUTO_BET_CONFIG,
    ...state.config,
    ...partial,
  };

  merged.enabled = Boolean(merged.enabled);
  merged.mode = merged.mode === 'away' ? 'away' : 'home';
  merged.bookmaker = merged.bookmaker === 'Bet365' ? 'Bet365' : 'Betano';

  const allowedMarkets = new Set([
    'OVER_1_5',
    'FAV_WIN',
    'FAV_DC',
    'HOME_WIN',
    'AWAY_WIN',
    'DC_1X',
    'DC_X2',
  ]);
  if (!allowedMarkets.has(merged.market)) {
    merged.market = 'OVER_1_5';
  }

  const parsedStake = Number(merged.stake);
  merged.stake = !isNaN(parsedStake) && parsedStake > 0 ? Number(parsedStake.toFixed(2)) : 20;

  const parsedOdd = Number(merged.defaultOdd);
  merged.defaultOdd = !isNaN(parsedOdd) && parsedOdd >= 1.01 ? Number(parsedOdd.toFixed(2)) : 2.0;

  // Strictly enforce max 3 games per ticket
  merged.maxGamesPerTicket = 3;

  return merged;
}

function pruneOldHistory(history: Record<string, string[]>, todayStr: string): Record<string, string[]> {
  const minDate = addDaysToDateStr(todayStr, -7);
  const next: Record<string, string[]> = {};
  for (const [key, val] of Object.entries(history || {})) {
    const datePart = key.split('__')[0];
    if (datePart && datePart >= minDate && Array.isArray(val)) {
      next[key] = val;
    }
  }
  return next;
}

function saveStateToDisk() {
  try {
    fs.writeFileSync(AUTO_BET_STATE_FILE, JSON.stringify(state, null, 2), 'utf-8');
  } catch (err) {
    console.warn('[AutoBet] Could not write local autoBetState.json:', err);
  }
}

async function saveStateToSupabase() {
  try {
    await executeSupabaseWithRetry(() =>
      supabaseAdmin
        .from('notification_settings')
        .upsert({
          id: SUPABASE_SETTINGS_ROW_ID,
          settings: state,
          updated_at: new Date().toISOString(),
        })
    );
  } catch (err) {
    console.warn('[AutoBet] Could not persist state to Supabase:', err);
  }
}

export async function loadAutoBetState(): Promise<PersistedAutoBetState> {
  if (stateLoaded) return state;

  // 1. Load from disk first for instant fallback
  try {
    if (fs.existsSync(AUTO_BET_STATE_FILE)) {
      const raw = fs.readFileSync(AUTO_BET_STATE_FILE, 'utf-8');
      const parsed = JSON.parse(raw);
      if (parsed && parsed.config) {
        state = {
          config: sanitizeConfig(parsed.config),
          generatedHistory: parsed.generatedHistory || {},
        };
      }
    }
  } catch (err) {
    console.warn('[AutoBet] Error reading local autoBetState.json:', err);
  }

  // 2. Load from Supabase (authoritative across restarts/deploys)
  try {
    const { data } = await executeSupabaseWithRetry(() =>
      supabaseAdmin
        .from('notification_settings')
        .select('settings')
        .eq('id', SUPABASE_SETTINGS_ROW_ID)
        .maybeSingle()
    );

    if (data && data.settings) {
      const remote = data.settings as any;
      if (remote.config) {
        state = {
          config: sanitizeConfig(remote.config),
          generatedHistory: {
            ...(state.generatedHistory || {}),
            ...(remote.generatedHistory || {}),
          },
        };
        saveStateToDisk();
        console.log(
          `[AutoBet] Loaded configuration from Supabase (enabled=${state.config.enabled}, mode=${state.config.mode}).`
        );
      }
    }
  } catch (err) {
    console.warn('[AutoBet] Error loading state from Supabase, using local/default state:', err);
  }

  stateLoaded = true;
  return state;
}

export async function getAutoBetConfig(): Promise<AutoBetConfig> {
  await loadAutoBetState();
  return { ...state.config };
}

export async function updateAutoBetConfig(
  partial: Partial<AutoBetConfig>
): Promise<AutoBetConfig> {
  await loadAutoBetState();
  const prevEnabled = state.config.enabled;
  const prevMode = state.config.mode;
  const nextConfig = sanitizeConfig({
    ...partial,
    updatedAt: new Date().toISOString(),
  });
  state.config = nextConfig;

  if ((!prevEnabled && nextConfig.enabled) || prevMode !== nextConfig.mode) {
    const todayKey = `${getBrasiliaTodayStr()}__${nextConfig.mode}`;
    if (state.generatedHistory && state.generatedHistory[todayKey]) {
      delete state.generatedHistory[todayKey];
    }
  }

  saveStateToDisk();
  await saveStateToSupabase();
  return { ...state.config };
}

async function getActiveFavoritesList(): Promise<FavoriteClubEntry[]> {
  try {
    const shared = await fetchSharedFavorites();
    if (shared && Array.isArray(shared) && shared.length > 0) {
      return shared;
    }
  } catch {
    // Fallback to curated master list
  }
  return USER_FAVORITE_CLUBS_DATA;
}

export async function getAutoBetPreview(
  dateStr = getBrasiliaTodayStr(),
  overrideConfig?: Partial<AutoBetConfig>
): Promise<AutoBetPreview> {
  await loadAutoBetState();
  const effectiveConfig = overrideConfig
    ? sanitizeConfig(overrideConfig)
    : state.config;

  const [favoritesList, matches, existingBets] = await Promise.all([
    getActiveFavoritesList(),
    scrapeFotMobMatchesByDate(dateStr).catch(() => []),
    fetchUserBets().catch(() => []),
  ]);

  return buildAutoBetPreview(
    Array.isArray(matches) ? matches : [],
    dateStr,
    effectiveConfig,
    favoritesList,
    Array.isArray(existingBets) ? existingBets : []
  );
}

/**
 * Core daily automation runner.
 * Identifies valid confirmed favorite matches for `dateStr` matching configured mode ('home' | 'away'),
 * groups them into tickets of up to 3 games (prioritizing triples, then 2 or 1),
 * prevents duplicate matches/tickets, and saves them directly to `user_bets` in Supabase.
 */
export async function runDailyAutoBetting(options?: {
  dateStr?: string;
  manualTrigger?: boolean;
}): Promise<AutoBetRunResult> {
  if (activeRunPromise) {
    return activeRunPromise;
  }

  activeRunPromise = (async () => {
    await loadAutoBetState();
    const todayStr = options?.dateStr || getBrasiliaTodayStr();
    const config = state.config;

    const favoritesList = await getActiveFavoritesList();
    const rawMatches = await scrapeFotMobMatchesByDate(todayStr).catch(() => []);
    const matches: Match[] = Array.isArray(rawMatches) ? rawMatches : [];

    // Fetch existing bets; if Supabase failed (returned null), abort safely to avoid duplicates
    const existingBets = await fetchUserBets();
    if (existingBets === null) {
      const emptyPreview = buildAutoBetPreview(matches, todayStr, config, favoritesList, []);
      return {
        success: false,
        date: todayStr,
        createdBets: [],
        skippedReason: 'Não foi possível consultar apostas existentes no banco.',
        preview: emptyPreview,
      };
    }

    const preview = buildAutoBetPreview(matches, todayStr, config, favoritesList, existingBets);

    if (!config.enabled && !options?.manualTrigger) {
      return {
        success: true,
        date: todayStr,
        createdBets: [],
        skippedReason: 'Automação desativada.',
        preview,
      };
    }

    const historyKey = `${todayStr}__${config.mode}`;
    // On background daemon ticks, also respect generatedHistory so manually deleted bets are not resurrected on the same day.
    // On explicit manual trigger, rely on `existingBets` deduplication so the user can regenerate if they deleted a ticket.
    const blockedKeys = options?.manualTrigger
      ? new Set<string>()
      : new Set<string>(state.generatedHistory[historyKey] || []);

    const candidates = getAutoBetCandidates(
      matches,
      todayStr,
      config.mode,
      favoritesList,
      existingBets,
      blockedKeys
    );

    const eligibleMatches = candidates
      .filter((c) => !c.alreadyInBet)
      .map((c) => c.match);

    if (eligibleMatches.length === 0) {
      state.config = {
        ...state.config,
        lastRunDate: todayStr,
        lastRunAt: new Date().toISOString(),
        lastCreatedCount: 0,
      };
      saveStateToDisk();
      await saveStateToSupabase();

      return {
        success: true,
        date: todayStr,
        createdBets: [],
        skippedReason:
          candidates.length > 0
            ? 'Todos os jogos qualificados de hoje já possuem bilhete registrado.'
            : 'Nenhum jogo válido encontrado na programação de hoje para o critério selecionado.',
        preview,
      };
    }

    // Group into tickets of max 3 games (prioritizing 3, remainder 2 or 1)
    const chunks = chunkMatchesIntoTickets(eligibleMatches, 3);
    const newBets = buildAutoBetItemsFromChunks(chunks, todayStr, config);

    const createdBets: BetItem[] = [];
    const newlyRecordedKeys = new Set<string>(state.generatedHistory[historyKey] || []);

    for (const bet of newBets) {
      // Double-check ID collision against existingBets
      if (existingBets.some((eb) => eb.id === bet.id)) {
        continue;
      }

      const saved = await saveUserBet(bet);
      if (saved) {
        createdBets.push(bet);
        for (const leg of bet.legs || []) {
          if (leg.matchId) newlyRecordedKeys.add(String(leg.matchId));
          const n1 = normalizeTeamName(leg.team1 || '');
          const n2 = normalizeTeamName(leg.team2 || '');
          if (n1 && n2) newlyRecordedKeys.add(`${n1}___${n2}`);
        }
      }
    }

    state.generatedHistory = pruneOldHistory(
      {
        ...state.generatedHistory,
        [historyKey]: Array.from(newlyRecordedKeys),
      },
      todayStr
    );

    state.config = {
      ...state.config,
      lastRunDate: todayStr,
      lastRunAt: new Date().toISOString(),
      lastCreatedCount: createdBets.length,
    };

    saveStateToDisk();
    await saveStateToSupabase();

    if (createdBets.length > 0) {
      console.log(
        `[AutoBet] Created ${createdBets.length} automatic ticket(s) for ${todayStr} (mode=${config.mode}, matches=${eligibleMatches.length}).`
      );
    }

    const updatedPreview = buildAutoBetPreview(
      matches,
      todayStr,
      config,
      favoritesList,
      [...existingBets, ...createdBets]
    );

    return {
      success: true,
      date: todayStr,
      createdBets,
      preview: updatedPreview,
    };
  })();

  try {
    return await activeRunPromise;
  } finally {
    activeRunPromise = null;
  }
}

/**
 * Background GREEN / RED settlement synchronizer.
 * Evaluates all pending bets in `user_bets` (both manual and auto-generated)
 * against official FotMob daily match feeds and persists status/score updates to Supabase.
 */
export async function syncPendingBetsInBackground(): Promise<{
  updatedCount: number;
  settledBets: BetItem[];
}> {
  if (activeSyncPromise) {
    return activeSyncPromise;
  }

  activeSyncPromise = (async () => {
    const allBets = await fetchUserBets();
    if (!allBets || allBets.length === 0) {
      return { updatedCount: 0, settledBets: [] };
    }

    const todayStr = getBrasiliaTodayStr();
    const minSyncDate = addDaysToDateStr(todayStr, -14);

    // Collect bets that are still pending or have pending legs
    const betsToCheck = allBets.filter(
      (b) =>
        b.status === 'Pendente' ||
        (Array.isArray(b.legs) && b.legs.some((l) => l.status === 'pending'))
    );

    if (betsToCheck.length === 0) {
      return { updatedCount: 0, settledBets: [] };
    }

    const datesToFetch = new Set<string>();
    for (const bet of betsToCheck) {
      if (bet.date && bet.date >= minSyncDate) {
        datesToFetch.add(bet.date);
      }
      if (Array.isArray(bet.legs)) {
        for (const leg of bet.legs) {
          const d = leg.date || bet.date;
          if (d && d >= minSyncDate) {
            datesToFetch.add(d);
          }
        }
      }
    }

    if (datesToFetch.size === 0) {
      datesToFetch.add(todayStr);
    }

    const allMatchesPool: Match[] = [];
    await Promise.all(
      Array.from(datesToFetch).map(async (d) => {
        try {
          const dayMatches = await scrapeFotMobMatchesByDate(d);
          if (Array.isArray(dayMatches)) {
            allMatchesPool.push(...dayMatches);
          }
        } catch {
          // Ignore transient date scrape failures
        }
      })
    );

    if (allMatchesPool.length === 0) {
      return { updatedCount: 0, settledBets: [] };
    }

    let updatedCount = 0;
    const settledBets: BetItem[] = [];

    for (const bet of betsToCheck) {
      const { updatedBet, changed } = syncBetWithMatches(bet, allMatchesPool);
      if (changed) {
        const saved = await saveUserBet(updatedBet);
        if (saved) {
          updatedCount++;
          if (
            bet.status === 'Pendente' &&
            (updatedBet.status === 'Ganha' || updatedBet.status === 'Perdida')
          ) {
            settledBets.push(updatedBet);
          }
        }
      }
    }

    if (updatedCount > 0) {
      console.log(`[AutoBet Sync] Synchronized and persisted ${updatedCount} bet(s) in background.`);
    }

    return { updatedCount, settledBets };
  })();

  try {
    return await activeSyncPromise;
  } finally {
    activeSyncPromise = null;
  }
}
