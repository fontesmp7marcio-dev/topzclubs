export const normalizeTeamName = (name: string): string => {
  return name
    .toLowerCase()
    .normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    .replace(/ FC$/i, '')
    .replace(/^FC /i, '')
    .trim();
};
